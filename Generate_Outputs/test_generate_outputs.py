import os
import shutil
from glob import glob

import pytest

# Intermediate files deleted after a run to save space
INTERMEDIATE_FILES = ['*.mat', '*_Sub.nii.gz', '*FullElasticSolution.nii.gz', '*T1W_Resampled.nii.gz',
                      '*AllCombinations.h5', '*-PRF-*.nii.gz', '*DataForSim.h5', '*Sub_NORM.nii.gz',
                      'CT.nii.gz', 'CT_InT1.nii.gz', 'm2m_*', '*FullElasticSolutionPhase.nii.gz', 'T1*.nii.gz']

@pytest.mark.generate_outputs
def test_generate_valid_outputs(qtbot,monkeypatch,request,image_to_base64,mock_confirm_pseudoct,check_os,pipeline_case):
    """Saves outputs directly in <gen_output_folder>/<case_id>. Folders already generated by the same
    BabelBrain commit and inputs are reused (BABEL_PYTEST_REGENERATE=1 forces a rerun)."""
    import Tests.pipeline_helpers as rh

    request.node.screenshots = []
    case = pipeline_case
    if rh.saved_outputs_reusable('', case):
        pytest.skip(f"Outputs already generated in {rh.case_output_dir('', case)}")

    outdir = rh.ensure_case_outputs(qtbot, monkeypatch, '', case, request.node.screenshots, image_to_base64)

    for pattern in INTERMEDIATE_FILES:
        for f in glob(os.path.join(str(outdir), pattern)):
            if os.path.isfile(f):
                os.remove(f)
            else:
                shutil.rmtree(f)
